function d(
  n: number,
  title: string,
  minutes: number,
  task: string,
  extra: Partial<WeekPlan["days"][0]> = {},
): WeekPlan["days"][0] {
  return { d: n, title, minutes, task, ...extra };
}

function week(
  n: number,
  phase: Phase,
  title: string,
  goal: string,
  days: WeekPlan["days"],
  listen: WeekPlan["listen"],
  kuliev: string,
  checkpoint: string,
  letters?: string[],
): WeekPlan {
  return { n, phase, title, goal, days, listen, kuliev, checkpoint, letters };
}

